async def insert_latency_events(db: AsyncSession, rows: list[dict[str, Any]]) -> None:
    """Bulk insert — the batched latency writer's flush path. A no-op on an empty batch so the
    periodic flush timer doesn't touch the DB on a quiet connection."""
    if not rows:
        return
    now = datetime.now(UTC)
    host_class = get_settings().host_class
    prepared = [
        {"id": uuid7(), "host_class": host_class, **row, "created_at": now, "updated_at": now}
        for row in rows
    ]
    await db.execute(insert(latency_events), prepared)
    await db.commit()


